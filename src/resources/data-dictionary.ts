export function renderDataDictionary(asOfDate: string): string {
  const lines: string[] = [
    '# Loan Portfolio — Schema & Data Dictionary',
    '',
    `**Data as of:** ${asOfDate}. All data is **synthetic** (generated by a seed script); no real customers.`,
    '',
    '## Conventions',
    '- Money is in USD (stored internally as integer cents). Rates are percentages (6.25 = 6.25%).',
    '- Dates are ISO `YYYY-MM-DD`. "As of" metrics are computed at the data as-of date above.',
    '- Columns marked **PII** are masked (e.g. `J*** S***`) unless the caller has the `admin` role.',
    '  Masking is enforced in the data layer and cannot be bypassed through tool arguments.',
    '',
    '## Tables',
  ];
  for (const t of TABLES) {
    lines.push(
      '',
      `### ${t.name}`,
      t.description,
      '',
      '| Column | Type | Description |',
      '|---|---|---|',
    );
    for (const c of t.columns) {
      lines.push(`| ${c.name}${c.pii ? ' **(PII)**' : ''} | ${c.type} | ${c.description} |`);
    }
  }
  lines.push(
    '',
    '## Relationships',
    '- customers 1 — * loans',
    '- loans 1 — * payments',
    '- loans 1 — * risk_ratings',
  );
  lines.push(
    '',
    '## Metrics',
    'Call the `explain_metric` tool for full detail.',
    '',
    '| Id | Formula |',
    '|---|---|',
  );
  for (const m of METRICS) lines.push(`| \`${m.id}\` | ${m.formula} |`);
  return lines.join('\n');
}
